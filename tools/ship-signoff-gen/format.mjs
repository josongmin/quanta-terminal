#!/usr/bin/env node
/**
 * format.mjs — turn a gate-result array into a SHIP_SIGNOFF.md document.
 *
 * Structure mirrors the hand-written docs/plans/0005-sota-convergence/SHIP_SIGNOFF.md:
 *   - Title + metadata block (date, commit, status)
 *   - Executive summary (auto-derived from gate counts)
 *   - Gate-by-gate table
 *   - Score line
 *   - Auto-generation footer
 */

/** Format one ISO date (YYYY-MM-DD) from a Date or a fallback. */
export function formatDate(d = new Date()) {
  const y = d.getUTCFullYear();
  const m = String(d.getUTCMonth() + 1).padStart(2, '0');
  const day = String(d.getUTCDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

/** Aggregate status line: SHIP / YELLOW / RED based on worst verdict. */
export function aggregateStatus(gates) {
  const red = gates.filter((g) => g.verdict === 'RED').length;
  const yellow = gates.filter((g) => g.verdict === 'YELLOW').length;
  const deferred = gates.filter((g) => g.verdict === 'DEFERRED').length;
  const green = gates.filter((g) => g.verdict === 'GREEN').length;
  if (red > 0) return { label: 'DO NOT SHIP', green, yellow, red, deferred };
  if (yellow > 0)
    return { label: 'SHIP TO STAGING', green, yellow, red, deferred };
  return { label: 'SHIP TO STAGING', green, yellow, red, deferred };
}

/** Render a gate's verdict cell — keeps identical vocabulary to the hand-written doc. */
function verdictCell(v) {
  if (v === 'DEFERRED') return '**DEFERRED**';
  return v;
}

/** Render the full SHIP_SIGNOFF.md body. */
export function formatSignoff(gates, { date, commit, auditor = 'automated' } = {}) {
  const dateStr = date || formatDate();
  const commitStr = commit || '(unknown)';
  const agg = aggregateStatus(gates);
  const header = `# Plan 0005 P0 — Ship Sign-off

- **Date**: ${dateStr}
- **Commit**: \`${commitStr}\`
- **Auditor**: ${auditor}
- **Status**: **${agg.label}** (${agg.green}/${gates.length} GREEN, ${agg.yellow} YELLOW, ${agg.red} RED${agg.deferred ? `, ${agg.deferred} deferred` : ''})

## Executive summary

Auto-generated by \`tools/ship-signoff-gen\` (Plan 0005 P1-I). Each gate row
below was produced by running the gate's underlying command or static
check against the current tree. See the footer for the generator commit.

---

## Gate-by-gate

| # | Description | Verdict | Evidence |
|---|-------------|---------|----------|
`;
  const rows = gates
    .map(
      (g) =>
        `| ${g.id} | ${escapeCell(g.title)} | ${verdictCell(g.verdict)} | ${escapeCell(g.evidence)} |`,
    )
    .join('\n');
  const score = `

**Score: ${agg.green} / ${gates.length} GREEN, ${agg.yellow} YELLOW, ${agg.deferred} DEFERRED, ${agg.red} RED.**

---

## Automation provenance

Generated by \`tools/ship-signoff-gen/index.mjs\`. Drift between this
generated output and the committed \`SHIP_SIGNOFF.md\` is detected by the
\`ship-signoff-weekly\` GH Action, which opens an issue on any
GREEN → YELLOW or YELLOW → RED flip.

To regenerate locally, run \`pnpm check:signoff\`.
`;
  return header + rows + score;
}

function escapeCell(s) {
  if (!s) return '';
  return String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
}
